// scriptc has no JSON or text imports, so the schemas are embedded as string constants.
const read = (name: string) => Bun.file(`schemas/${name}.schema.json`).text();
const out = `// Generated by scripts/gen-schemas.ts from schemas/*.json. Do not edit.
export const REPORT_SCHEMA = ${JSON.stringify(JSON.stringify(JSON.parse(await read("report"))))};
export const REVIEW_SCHEMA = ${JSON.stringify(JSON.stringify(JSON.parse(await read("review"))))};
`;
await Bun.write("src/schemas.ts", out);
